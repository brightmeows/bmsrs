//! Tokenizer error types: the unified error type for the BMS tokenizer.

use std::fmt;
use std::num::NonZeroUsize;
use std::num::ParseFloatError;
use std::num::ParseIntError;

use thiserror::Error;

/// Errors that can occur while tokenizing BMS.
///
/// Every variant carries the original input `value`, so callers can inspect or
/// display the raw text that caused the failure.
#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub enum BmsTokenizeError {
    /// The measure number in a channel line is not a valid 3-digit value.
    #[error("invalid measure number: \"{value}\"")]
    InvalidMeasure {
        /// Original measure string that failed validation.
        value: String,
    },
    /// The channel number in a channel line is not a valid 2-character value.
    #[error("invalid channel number: \"{value}\"")]
    InvalidChannel {
        /// Original channel string that failed validation.
        value: String,
    },
    /// An integer field could not be parsed.
    #[error("invalid integer: \"{value}\"")]
    InvalidInteger {
        /// Original input that could not be parsed as an integer.
        value: String,
    },
    /// A floating-point field could not be parsed.
    #[error("invalid float: \"{value}\"")]
    InvalidFloat {
        /// Original input that could not be parsed as a float.
        value: String,
    },
    /// The input is not a recognized value in its context.
    ///
    /// Covers both "out of range" (the value has the right shape but exceeds
    /// the valid range) and "unrecognized" (the value does not match any known
    /// literal enum option). When no specific valid set is available,
    /// `expected` is the empty string.
    #[error("value out of range: \"{value}\" for {context} (expected {expected})")]
    OutOfRange {
        /// Header command name (for example, `"#DIFFICULTY"`).
        context: &'static str,
        /// Original input that is out of range or unrecognized.
        value: String,
        /// Description of the valid range (for example, `"1-5"`, `"1 or 2"`),
        /// or the empty string when no specific hint is available.
        expected: &'static str,
    },
}

/// Conversion from `FromStr::Err` to [`BmsTokenizeError`].
///
/// The `#[derive(BmsTokenAttr)]` macro calls this trait to convert any parse
/// error into the tokenizer's unified error type. Implementations are provided
/// for [`ParseIntError`], [`ParseFloatError`], [`ParseBmsValueError`], and, for
/// custom `FromStr` implementations that already produce `BmsTokenizeError`,
/// [`BmsTokenizeError`] itself (identity).
pub trait IntoTokensError {
    /// Convert this error into a `BmsTokenizeError`.
    ///
    /// * `context`: header command name (for example, `"#PLAYER"`).
    /// * `value`: original input string that failed to parse.
    fn into_error(self, context: &'static str, value: String) -> BmsTokenizeError;
}

impl IntoTokensError for BmsTokenizeError {
    fn into_error(self, context: &'static str, value: String) -> Self {
        match self {
            Self::OutOfRange {
                context: "",
                expected,
                ..
            } => Self::OutOfRange {
                context,
                value,
                expected,
            },
            other => other,
        }
    }
}

impl IntoTokensError for ParseIntError {
    fn into_error(self, _context: &'static str, value: String) -> BmsTokenizeError {
        BmsTokenizeError::InvalidInteger { value }
    }
}

impl IntoTokensError for ParseFloatError {
    fn into_error(self, _context: &'static str, value: String) -> BmsTokenizeError {
        BmsTokenizeError::InvalidFloat { value }
    }
}

impl IntoTokensError for ParseBmsValueError {
    fn into_error(self, context: &'static str, value: String) -> BmsTokenizeError {
        BmsTokenizeError::OutOfRange {
            context,
            value,
            expected: self.0,
        }
    }
}

/// The input cannot be parsed as the expected BMS value type.
///
/// Returned by the [`std::str::FromStr`] implementation generated by
/// `#[derive(BmsTokenAttr)]` in literal mode.
///
/// When non-empty, the string provides a readable hint about the expected value
/// (for example, `"expected 1 or 2"`).
#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub struct ParseBmsValueError(pub &'static str);

impl fmt::Display for ParseBmsValueError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if self.0.is_empty() {
            write!(f, "invalid BMS value")
        } else {
            write!(f, "expected {}", self.0)
        }
    }
}

/// Error type for `TryFrom` conversions between token types.
///
/// Used when extracting a header or message from a
/// [`BmsToken`](crate::BmsToken) or a
/// `(NonZeroUsize, Result<BmsToken, BmsTokenizeError>)` tuple.
///
/// **Note**: sub-enum extraction (such as `BmsHeader::try_unwrap_gameplay`) no
/// longer reports errors through this type; it returns
/// [`derive_more::TryUnwrapError`] instead. The `WrongHeaderType` variant was
/// removed during the `0.1.0` cycle.
#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub enum BmsTryFromError {
    /// The source `(NonZeroUsize, Result<BmsToken, ...>)` contained an `Err`.
    #[error("tokenization error on line {line}: {error}")]
    TokenizationError {
        /// One-based line number where the error occurred.
        line: NonZeroUsize,
        /// Underlying tokenizer error.
        error: BmsTokenizeError,
    },
    /// The `BmsToken` is a `Message`, not a `Header`.
    #[error("expected a header, but the token is a channel message")]
    NotAHeader,
    /// The `BmsToken` is a `Header`, not a `Message`.
    #[error("expected a message, but the token is a header")]
    NotAMessage,
}
